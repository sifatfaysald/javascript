// Arithmetic operators

const firstNumber = 10;
const secondNumber = 3;

console.log(firstNumber + secondNumber); // 13
console.log(firstNumber - secondNumber); // 7
console.log(firstNumber * secondNumber); // 30
console.log(firstNumber / secondNumber); // 3.333...
console.log(firstNumber % secondNumber); // 1 — remainder
console.log(firstNumber ** secondNumber); // 1000 — exponentiation

// Increment / decrement
let count = 5;
console.log(count++); // 5 — returns then increments
console.log(count); // 6
console.log(++count); // 7 — increments then returns
console.log(count--); // 7
console.log(count); // 6
